/**
 * PARITY-01…PARITY-10 — the backend against the validated frontend engine.
 *
 * This is the point of Phase 5. The frontend analytical engine is already
 * validated; moving it to the backend only means anything if the two produce
 * the same answers for the same inputs. So the fixture records what the
 * ENGINE says — generated by `scripts/export-analysis-parity-fixture.mjs`,
 * which runs on the frontend side where those modules are loadable — and
 * every assertion here compares a STRUCTURED value against it.
 *
 * Nothing here compares a rendered sentence. Prose is presentation; the
 * numbers and the finding identities are the analysis.
 *
 * TWO KNOWN GAPS, asserted as exactly two:
 *   · `wtp`    — the hedonic willingness-to-pay model
 *   · `bridge` — maps the three strategy prices into the analysis
 * Both are the pricing recommendation rather than inputs to it. The test
 * below requires the difference to be precisely these and nothing else.
 */

type Fixture = {
  notMigrated: string[];
  caseCount: number;
  cases: Array<Json>;
};

/**
 * Read eagerly, at module scope.
 *
 * `describe` bodies run while the module is evaluating — before any
 * `before` hook — and each product needs its own named test rather than one
 * loop reporting a single pass or fail for all ten. So the fixture has to be
 * available synchronously here.
 */
const FIXTURE_PATH = join(fileURLToPath(new URL(".", import.meta.url)), "fixtures", "analysis-parity.json");
const fixture = JSON.parse(readFileSync(FIXTURE_PATH, "utf8")) as Fixture;
const loadCases = (): Json[] => fixture.cases;

let h: Harness;
let token: string;

/** Floating point, not approximation: the two sides run the same arithmetic. */
const TOLERANCE = 1e-9;

const closeTo = (actual: unknown, expected: unknown, label: string) => {
  if (expected == null || actual == null) {
    assert.equal(actual ?? null, expected ?? null, label);
    return;
  }
  const a = Number(actual);
  const e = Number(expected);
  assert.ok(
    Math.abs(a - e) <= TOLERANCE,
    `${label}: backend ${a}, engine ${e} (difference ${Math.abs(a - e)}, tolerance ${TOLERANCE})`
  );
};

/**
 * Products the per-product reference date resolves differently from the
 * global one — the only ones where this fixture's global anchoring and the
 * backend's can disagree. Computed from the seeded data, not listed.
 */
let olderAnchor: Set<string> = new Set();

before(async () => {
  h = await createAnalysisTestApp(fixture.cases.map((c) => c.productId as string));
  ({ token } = await signIn(h, "parity@example.com"));
  olderAnchor = await productsWithOlderOwnAnchor(h.db);
});
after(async () => {
  await h.close();
});

const get = async (url: string) => {
  const res = await h.app.inject({ method: "GET", url: `/api/v1${url}`, headers: bearer(token), remoteAddress: "10.70.0.1" });
  return { status: res.statusCode, body: res.json() as Json };
};

/** Every page of the competitor endpoint, so membership can be compared whole. */
async function allCompetitors(productId: string): Promise<Json[]> {
  const out: Json[] = [];
  for (let page = 1; page <= 20; page++) {
    const { body } = await get(`/products/${productId}/competitors?page=${page}&pageSize=100`);
    out.push(...((body["data"] as Json[]) ?? []));
    if (!body["pagination"]?.hasNext) break;
  }
  return out;
}

/** The analysis over the product's WHOLE observed history, as the engine uses. */
async function fullAnalysis(testCase: Json): Promise<Json> {
  const history = testCase.history as Json | null;
  const query = history ? `?from=${history.firstDate}&to=${history.lastDate}` : "";
  const { status, body } = await get(`/products/${testCase.productId}/analysis${query}`);
  assert.equal(status, 200, `analysis for ${testCase.productId}`);
  return body["data"] as Json;
}

/* ================================================== competitive set parity */

describe("PARITY-01/02/03 — the competitive set", () => {
  it("the fixture covers the shapes the engine has to handle", () => {
    assert.equal(fixture.cases.length, 10);
    const levels = new Set(fixture.cases.map((c) => (c.competitiveSet as Json).coverage.level));
    assert.ok(levels.has("strong"), "a strong-coverage product");
    assert.ok(levels.has("insufficient"), "a refusal case");
    assert.ok(
      fixture.cases.some((c) => c.unitBasis != null),
      "a product where per-unit analysis is meaningful"
    );
    assert.ok(
      fixture.cases.some((c) => c.unitBasis == null),
      "a product where per-unit analysis must be suppressed"
    );
    assert.ok(
      fixture.cases.some((c) => (c.marketplaceRows as Json[]).length === 1),
      "a single-marketplace product"
    );
  });

  for (const testCase of loadCases()) {
    it(`PARITY-01 ${testCase.productId}: membership and tiers match the engine`, async () => {
      const expected = testCase.competitiveSet as Json;
      const actual = await allCompetitors(testCase.productId as string);

      // Membership, as a set: the backend may order within a tier by the same
      // rank but a difference in stable-sort tie-breaking is not a difference
      // in analysis.
      assert.deepEqual(
        actual.map((c) => c.productId).sort(),
        [...(expected.memberIds as string[])].sort(),
        `${testCase.productId}: competitive-set membership`
      );

      const tierOf = new Map(actual.map((c) => [c.productId as string, c.tier as string]));
      for (const id of expected.directIds as string[]) {
        assert.equal(tierOf.get(id), "direct", `${testCase.productId}: ${id} should be direct`);
      }
      for (const id of expected.comparableIds as string[]) {
        assert.equal(tierOf.get(id), "comparable", `${testCase.productId}: ${id} should be comparable`);
      }
    });

    it(`PARITY-02/03 ${testCase.productId}: similarity, evidence weight and their components match`, async () => {
      const expected = testCase.competitiveSet as Json;
      const actual = await allCompetitors(testCase.productId as string);
      const byId = new Map(actual.map((c) => [c.productId as string, c]));

      for (const member of expected.members as Json[]) {
        const got = byId.get(member.productId as string);
        assert.ok(got, `${testCase.productId}: ${member.productId} missing from the backend set`);
        const at = `${testCase.productId}/${member.productId}`;

        // The endpoint rounds similarity for transport; compare at that
        // precision rather than pretending to more.
        closeTo(got!.similarity, Math.round((member.similarity as number) * 10000) / 10000, `${at} similarity`);
        closeTo(got!.evidenceWeight, member.evidenceWeight, `${at} evidenceWeight`);
        closeTo(got!.currentPriceMinor, member.currentPriceMinor, `${at} currentPriceMinor`);
        assert.equal(got!.sharedMarketplaces, member.sharedMarketplaces, `${at} sharedMarketplaces`);
        assert.deepEqual([...(got!.marketplaceIds as string[])].sort(), member.marketplaceIds, `${at} marketplaces`);
        assert.equal(got!.rating, member.rating, `${at} rating`);
        assert.equal(got!.reviewCount, member.reviewCount, `${at} reviewCount`);
        assert.equal(got!.isSameFamily, member.isSameFamily, `${at} isSameFamily`);

        // The similarity components, so a matching total cannot hide two
        // compensating errors.
        const breakdown = got!.similarityBreakdown as Json;
        const wanted = member.breakdown as Json;
        closeTo(breakdown.specScore, wanted.specScore, `${at} specScore`);
        closeTo(breakdown.tierScore, wanted.tierScore, `${at} tierScore`);
        closeTo(breakdown.priceScore, wanted.priceScore, `${at} priceScore`);
        closeTo(breakdown.marketplaceScore, wanted.marketplaceScore, `${at} marketplaceScore`);

        closeTo((got!.dataQuality as Json).score, Math.round((member.qualityScore as number) * 1000) / 1000, `${at} quality`);

        const spec = got!.specificationMatch as Json;
        assert.equal(spec.match, member.specMatch, `${at} spec match count`);
        assert.equal(spec.partial, member.specPartial, `${at} spec partial count`);
        assert.equal(spec.differ, member.specDiffer, `${at} spec differ count`);
        assert.equal(spec.missing, member.specMissing, `${at} spec missing count`);
      }
    });
  }
});

