/* ================================================== findings and statistics */

describe("PARITY-06/09/10 — finding presence and absence", () => {
  for (const testCase of loadCases()) {
    it(`${testCase.productId}: produces exactly the engine's findings, less the two not migrated`, async () => {
      const data = await fullAnalysis(testCase);
      const actual = (data.findings as Json[]).map((f) => f.id as string).sort();
      const expected = (testCase.findingIds as string[]).filter((id) => !fixture.notMigrated.includes(id)).sort();

      // PARITY-09: nothing invented. PARITY-10: nothing legitimately
      // produced by the engine is missing. Both directions, one assertion.
      assert.deepEqual(actual, expected, `${testCase.productId}: findings`);
    });

    it(`${testCase.productId}: each finding keeps its dimension and direction`, async () => {
      const data = await fullAnalysis(testCase);
      const actual = new Map((data.findings as Json[]).map((f) => [f.id as string, f]));

      for (const finding of testCase.findings as Json[]) {
        if (fixture.notMigrated.includes(finding.id as string)) continue;
        const got = actual.get(finding.id as string);
        assert.ok(got, `${testCase.productId}: ${finding.id} missing`);
        assert.equal(got!.dimension, finding.dimension, `${finding.id} dimension`);
        assert.equal(got!.direction, finding.direction, `${finding.id} direction`);
      }
    });
  }

  it("the difference from the engine is EXACTLY the two recommendation findings", async () => {
    // Not "some findings differ" — precisely wtp and bridge, and nothing
    // else. Anything broader would let a genuine omission hide.
    assert.deepEqual([...fixture.notMigrated].sort(), ["bridge", "wtp"]);

    const missingAcrossAll = new Set<string>();
    for (const testCase of fixture.cases) {
      const data = await fullAnalysis(testCase);
      const actual = new Set((data.findings as Json[]).map((f) => f.id as string));
      for (const id of testCase.findingIds as string[]) if (!actual.has(id)) missingAcrossAll.add(id);
    }
    assert.deepEqual([...missingAcrossAll].sort(), ["wtp"], "only `wtp` is absent; `bridge` is not a finding");
  });
});

