describe("PARITY-05 — per-unit calculations", () => {
  for (const testCase of loadCases()) {
    it(`${testCase.productId}: unit basis and per-unit figures match`, async () => {
      const data = await fullAnalysis(testCase);
      const expected = testCase.unitBasis as Json | null;
      const actual = data.unitBasis as Json | null;

      if (expected == null) {
        // Suppression is the assertion: no quantity-bearing attribute means
        // no per-unit analysis, and inventing one is the error this guards.
        assert.equal(actual, null, `${testCase.productId}: per-unit analysis must be suppressed`);
        assert.ok(
          !(data.findings as Json[]).some((f) => f.id === "per_unit_reversal"),
          `${testCase.productId}: a per-unit finding without a unit basis`
        );
        return;
      }

      assert.ok(actual, `${testCase.productId}: unit basis missing`);
      assert.equal(actual!.key, expected.key, "unit key");
      assert.equal(actual!.unit, expected.unit, "unit");
      closeTo(actual!.value, expected.value, "unit value");

      const expectedComp = testCase.competitors as Json | null;
      if (!expectedComp) return;
      const actualComp = data.competitors as Json | null;
      assert.ok(actualComp, `${testCase.productId}: competitor analysis missing`);
      closeTo(actualComp!.ownUnitPriceMinor, expectedComp.ownUnitPriceMinor, "ownUnitPriceMinor");
      assert.deepEqual(
        [...(actualComp!.reversals as Json[])].map((r) => r.id).sort(),
        [...(expectedComp.reversalIds as string[])].sort(),
        `${testCase.productId}: per-unit reversals`
      );
    });
  }
});

