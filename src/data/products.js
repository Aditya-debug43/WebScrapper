export const products = [...curatedProducts, ...generatedProducts];

const productById = new Map(products.map((p) => [p.id, p]));

export function getProduct(productId) {
  return productById.get(productId) ?? null;
}

export function getVariantSiblings(productId) {
  const product = getProduct(productId);
  if (!product?.parentProductId) return [];
  return products.filter(
    (p) => p.parentProductId === product.parentProductId && p.id !== productId
  );
}

export function getPurchasableProducts() {
  return products.filter((p) => p.isPurchasable);
}
