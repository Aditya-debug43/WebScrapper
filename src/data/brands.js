// Brand is a first-class entity, not a text column on Product: the catalogue
// filters on it, and the recommendation engine uses `tier` as a real input to
// its product-strength scoring and to its comparable-set similarity.
//
// Brands are REAL brands that actually operate in these categories in India,
// not generated filler. That matters more than it might seem: `tier` has to
// mean something for brand-tier similarity to carry information, and it only
// means something if the brands are ones with genuine market positions. A list
// of invented names would give the tier axis nothing to encode.
//
// `tier` is the market position, not a quality judgement — "value" means the
// brand competes primarily on price in that category, "premium" that it
// sustains a price above the category norm.

