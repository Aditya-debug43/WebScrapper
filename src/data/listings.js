export const listings = [...curatedListings, ...generatedListings];

const listingById = new Map(listings.map((l) => [l.id, l]));
const listingsByProductId = (() => {
  const map = new Map();
  for (const l of listings) {
    let arr = map.get(l.productId);
    if (!arr) map.set(l.productId, (arr = []));
    arr.push(l);
  }
  return map;
})();

export function getListing(listingId) {
  return listingById.get(listingId) ?? null;
}

export function getListingsForProduct(productId) {
  return listingsByProductId.get(productId) ?? [];
}
